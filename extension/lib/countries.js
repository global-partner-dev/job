const normalized = new Set(ALLOWED_COUNTRIES.map((c) => c.trim().toLowerCase()));

/** @param {string} country */
export function isCountryAllowed(country) {
  if (!country?.trim()) return false;
  const key = country.trim().toLowerCase();
  if (key === 'ukraine' || key === 'ukraina') return false;
  return normalized.has(key);
}
